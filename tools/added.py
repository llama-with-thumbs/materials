# -*- coding: utf-8 -*-
"""Work out when each entry joined the catalogue, and write added.js.

There is no date field in data.js or plates.js, so the order comes from git: walk every
commit that touched either file, oldest first, and the first commit a given id appears
in is when it was added. Inside one commit the file order is kept, which is already add
order within each category. Ids that are not committed yet land at the end with
today's date. Cards and plates share one order, so a plate sorts among the cards that
were added around the same time.

Run from the repository root:  python tools/added.py
"""
import re
import subprocess
import sys
import os
import datetime

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ["data.js", "plates.js", "papers.js"]


def git(*args):
    out = subprocess.run(("git",) + args, cwd=ROOT, capture_output=True, check=True)
    return out.stdout.decode("utf-8", "replace")


def ids(text):
    return re.findall(r'\n  id: "([^"]+)"', text)


def show(sha, f):
    r = subprocess.run(("git", "show", "%s:%s" % (sha, f)), cwd=ROOT, capture_output=True)
    return r.stdout.decode("utf-8", "replace") if r.returncode == 0 else ""


commits = git("log", "--reverse", "--format=%H %cs", "--", *FILES).split("\n")
commits = [c.split(" ") for c in commits if c.strip()]

order = []          # (id, date) in the order the catalogue grew
seen = set()
for sha, date in commits:
    there = [i for f in FILES for i in ids(show(sha, f))]
    for i in there:
        if i not in seen:
            seen.add(i)
            order.append((i, date))
    print("%s  %s  %4d ids, %4d total" % (sha[:7], date, len(there), len(order)))

current = []
for f in FILES:
    p = os.path.join(ROOT, f)
    if os.path.exists(p):
        current += ids(open(p, encoding="utf-8").read())
today = datetime.date.today().isoformat()
for i in current:
    if i not in seen:
        seen.add(i)
        order.append((i, today))
        print("uncommitted: %s" % i)

live = set(current)
order = [(i, d) for i, d in order if i in live]          # drop ids that were renamed away
assert len(order) == len(current), (len(order), len(current))

body = "".join('  %s: "%s",\n' % (i, d) for i, d in order).rstrip(",\n") + "\n"
out = ("/* When each entry joined the catalogue, oldest first — generated by tools/added.py\n"
       "   from the git history of data.js and plates.js. Key order is the add order the page sorts by. */\n\n"
       "window.ADDED = {\n" + body + "};\n")
p = os.path.join(ROOT, "added.js")
open(p, "w", encoding="utf-8", newline="\n").write(out)
print("added.js: %d entries, %s .. %s" % (len(order), order[0][1], order[-1][1]))
